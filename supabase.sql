-- 1) เปิด Supabase > SQL Editor แล้ววางโค้ดนี้ จากนั้นกด Run
create table if not exists public.kingman_scores (
  id bigint generated by default as identity primary key,
  player_name text not null default 'KINGMAN' check (char_length(player_name) between 1 and 18),
  score integer not null check (score >= 0 and score <= 10000000),
  shells integer not null default 0 check (shells >= 0 and shells <= 1000000),
  created_at timestamptz not null default now()
);

alter table public.kingman_scores enable row level security;

-- ทุกคนอ่าน 10 อันดับได้
create policy "Scores are readable by everyone"
on public.kingman_scores for select
to anon, authenticated
using (true);

-- ผู้เล่นส่งคะแนนได้ โดยไม่ต้องล็อกอิน
create policy "Anyone can submit a score"
on public.kingman_scores for insert
to anon, authenticated
with check (
  char_length(player_name) between 1 and 18
  and score >= 0 and score <= 10000000
  and shells >= 0 and shells <= 1000000
);

create index if not exists kingman_scores_score_idx on public.kingman_scores (score desc);
